package javacore.chapter03.loop.exercise;

public class WhileLoopExample {
    public static void main(String[] args) {
        int loopCounter  =1;
        while(loopCounter <=1){
            System.out.println("Hello world " + loopCounter);
            loopCounter ++;

        }
        int n = 2;
        while(n <= 10){
            System.out.println(n);
            n+=2;
        }
    }
}
